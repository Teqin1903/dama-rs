// Writes deck/src/data.js: every number the deck shows, read from the files it cites.
// (results/ladder, results/ablation, results/mcts, results/arena.csv, deck/facts.json)
//   node deck/tools/data.js            from results/ and deck/facts.json
//   node deck/tools/data.js LOGDIR     also recounts deck/facts.json from replayed games with moves:
//     dama arena idqrot:n20000:w=texel1 tuned --games 160 --seed 1 --log LOGDIR/v10_v0.tsv --csv LOGDIR/a.csv
//     dama arena idqrot:n20000:w=texel1 idrot:n20000:w=texel1 --games 100 --seed 1 --log LOGDIR/v10_v10q.tsv --csv LOGDIR/a.csv
'use strict';
const fs = require('fs');
const path = require('path');

const deck = path.resolve(__dirname, '..');
const repo = path.resolve(deck, '..');
const read = (p) => fs.readFileSync(path.join(repo, p), 'utf8');

const ladder = JSON.parse(read('results/ladder/ladder.json'));
const ablation = JSON.parse(read('results/ablation/ablation.json'));
const mcts = JSON.parse(read('results/mcts/mcts.json'));

// results/arena.csv: the row of quiescence with the tuned (A3) weights, docs/ladder.md
const rows = read('results/arena.csv').trim().split('\n');
const head = rows[0].split(',');
const arena = rows.slice(1).map((l) => { const f = l.split(','); const o = {}; head.forEach((h, i) => (o[h] = f[i])); return o; });
const q = arena.filter((r) => r.a === 'idqrot:n20000' && r.b === 'idrot:n20000').pop();
if (!q) throw new Error('results/arena.csv has no row idqrot:n20000 against idrot:n20000');
const s = +q.score_pct / 100, se = +q.se_pct / 100;
const elo = (p) => 400 * Math.log10(p / (1 - p));
const qTuned = {
  version: q.version, games: +q.games, w: +q.wins, d: +q.draws, l: +q.losses, score: s,
  elo: elo(s), ci: [elo(s - 1.96 * se), elo(s + 1.96 * se)],
  draws: { repetition: +q.repetition, fifty: +q.fifty_quiet, one_each: +q.one_piece_each },
};

// Facts counted over replayed games (the stored game rows keep no moves).
const factsFile = path.join(deck, 'facts.json');
if (process.argv[2]) {
  const pkg = path.join(repo, 'site', 'pkg');
  const W = new Function(fs.readFileSync(path.join(pkg, 'dama_web.js'), 'utf8') + '\nreturn wasm_bindgen;')();
  W.initSync({ module: fs.readFileSync(path.join(pkg, 'dama_web_bg.wasm')) });
  const J = (x) => JSON.parse(x);
  const facts = { source: 'replayed ablation games (deck/tools/data.js)', sets: [] };
  for (const [file, name] of [['v10_v0.tsv', 'V10 against V0, games 0-159'], ['v10_v10q.tsv', 'V10 against V10 without quiescence, games 0-99']]) {
    const lines = fs.readFileSync(path.join(process.argv[2], file), 'utf8').trim().split('\n').slice(1);
    let pos = 0, legal = 0, caps = 0, single = 0;
    for (const line of lines) {
      const moves = line.split('\t')[6].split(' ');
      const ses = new W.Session();
      for (const m of moves) {
        const l = J(ses.legal());
        pos++; legal += l.length;
        if (l.length && l[0].captured.length) caps++;
        if (l.length === 1) single++;
        J(ses.play(m));
      }
    }
    facts.sets.push({ name, games: lines.length, positions: pos, legal_per_position: legal / pos, capture_share: caps / pos, single_share: single / pos });
  }
  fs.writeFileSync(factsFile, JSON.stringify(facts, null, 1) + '\n');
}
const facts = JSON.parse(fs.readFileSync(factsFile, 'utf8'));

const out = [
  '// Generated by deck/tools/data.js; do not edit. Sources: results/ladder/ladder.json,',
  '// results/ablation/ablation.json, results/mcts/mcts.json, results/arena.csv (quiescence with the tuned weights),',
  '// deck/facts.json.',
  `const LADDER = ${JSON.stringify(ladder)};`,
  `const ABLATION = ${JSON.stringify(ablation)};`,
  `const MCTS = ${JSON.stringify(mcts)};`,
  `const Q_TUNED = ${JSON.stringify(qTuned)};`,
  `const FACTS = ${JSON.stringify(facts)};`,
  '',
].join('\n');
fs.writeFileSync(path.join(deck, 'src', 'data.js'), out);
console.log(`wrote deck/src/data.js (${out.length} bytes); quiescence with tuned weights: ${qTuned.elo.toFixed(1)} [${qTuned.ci.map((x) => x.toFixed(0)).join(', ')}]`);
for (const f of facts.sets) console.log(`  ${f.name}: ${f.legal_per_position.toFixed(2)} legal moves per position, capture compulsory in ${(100 * f.capture_share).toFixed(1)}%`);
