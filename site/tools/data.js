// Writes data/results.js (window.LADDER and window.ABLATION) from results/ladder/ladder.json and
// results/ablation/ablation.json. A script file rather than fetch, so the page also works from file://.
// Run it after every `ladder rate`: node site/tools/data.js
'use strict';
const fs = require('fs');
const path = require('path');

const site = path.resolve(__dirname, '..');
const repo = path.resolve(site, '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(repo, p), 'utf8'));

const ladder = read('results/ladder/ladder.json');
const ablation = read('results/ablation/ablation.json');
const minute = read('results/minute/minute.json');
const out = [
  '// Generated by site/tools/data.js; do not edit. Sources:',
  `//   results/ladder/ladder.json (version ${ladder.meta.commit}, ${ladder.meta.date})`,
  `//   results/ablation/ablation.json (version ${ablation.meta.commit}, ${ablation.meta.date})`,
  `//   results/minute/minute.json (version ${minute.version})`,
  `window.LADDER = ${JSON.stringify(ladder)};`,
  `window.ABLATION = ${JSON.stringify(ablation)};`,
  `window.MINUTE = ${JSON.stringify(minute)};`,
  '',
].join('\n');
fs.mkdirSync(path.join(site, 'data'), { recursive: true });
fs.writeFileSync(path.join(site, 'data', 'results.js'), out);
console.log(`wrote site/data/results.js (${out.length} bytes)`);
